-- Run manually in the Supabase SQL Editor for this project's public.message table.
-- Existing messages are preserved. All rows in this table are public guestbook content.
begin;

create table if not exists public.message (
  id bigint generated by default as identity primary key,
  content text not null,
  created_at timestamptz not null default now()
);

-- NOT VALID preserves old rows; PostgreSQL still checks every new/updated row.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.message'::regclass and conname = 'guestbook_content_length'
  ) then
    alter table public.message add constraint guestbook_content_length
      check (content is not null and content ~ '[^[:space:]]' and char_length(content) <= 1000) not valid;
  end if;
end $$;

create index if not exists guestbook_created_at_id_idx on public.message (created_at desc, id desc);
alter table public.message enable row level security;

-- Public visitors can read only display fields and submit only content.
-- Owners can moderate/delete messages in the Supabase dashboard.
revoke all on public.message from public, anon, authenticated;
grant usage on schema public to anon;
grant select (id, content, created_at), insert (content) on public.message to anon;

do $$
declare
  sequence_name text;
begin
  sequence_name := pg_get_serial_sequence('public.message', 'id');
  if sequence_name is not null then
    execute format('grant usage on sequence %s to anon', sequence_name);
  end if;
end $$;

drop policy if exists guestbook_public_read on public.message;
create policy guestbook_public_read on public.message for select to anon using (true);
drop policy if exists guestbook_public_insert on public.message;
create policy guestbook_public_insert on public.message for insert to anon
  with check (content is not null and content ~ '[^[:space:]]' and char_length(content) <= 1000);

-- Realtime powers the "留言有更新" prompt; normal loading works without it.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
    and not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'message'
    ) then
    alter publication supabase_realtime add table public.message;
  end if;
end $$;

commit;
